import { expect, test } from '@playwright/test';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

for (const mode of ['disk', 'static hosting']) {
  test(`native artefact site retains supplied labels and front-matter priority from ${mode}`, async ({ page }) => {
    const errors = [];
    const external = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => {
      const url = request.url();
      if (/^https?:/.test(url) && !url.startsWith('http://127.0.0.1:')) external.push(url);
    });
    const relative = 'artifacts/native/validation/artefact-site/index.html';
    await page.goto(mode === 'disk' ? pathToFileURL(path.resolve(relative)).href : '/' + relative);
    await expect(page.locator('#siteTitle')).toHaveText('Artefact review site');
    await page.locator('#nav').getByRole('link', { name: 'Reviewer home', exact: true }).click();
    await expect(page.locator('#docMeta')).toContainText('Local review');
    await expect(page.locator('#docMeta')).toContainText('Evidence labels are displayed as supplied by the bundle.');
    await expect(page.locator('#docMeta')).toContainText('Candidate findings remain candidate findings.');
    await page.locator('#nav').getByRole('link', { name: 'Candidate Risk', exact: true }).click();
    await expect(page.locator('#docMeta')).toContainText('candidate finding');
    await expect(page.locator('#docMeta')).not.toContainText('confirmed finding');
    await page.locator('#nav').getByRole('link', { name: 'Confirmed Control', exact: true }).click();
    await expect(page.locator('#docMeta')).toContainText('confirmed finding');
    await page.locator('#searchInput').fill('candidate finding');
    await expect(page.locator('#searchResults .search-result')).not.toHaveCount(0);
    await page.locator('#searchInput').fill('');
    await page.locator('#nav').getByRole('link', { name: 'Candidate Risk', exact: true }).click();
    await page.screenshot({ path: test.info().outputPath('native-artefact-site.png'), fullPage: true });
    expect(errors).toEqual([]);
    expect(external).toEqual([]);
  });

  test(`native Docs Site navigation, search, images and themes work from ${mode}`, async ({ page }) => {
    const errors = [];
    const external = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => {
      const url = request.url();
      if (/^https?:/.test(url) && !url.startsWith('http://127.0.0.1:')) external.push(url);
    });
    const relative = 'artifacts/native/validation/docs-site/index.html';
    await page.goto(mode === 'disk' ? pathToFileURL(path.resolve(relative)).href : '/' + relative);
    await expect(page.locator('#siteTitle')).toHaveText('Native handbook');
    await expect(page.locator('#content h1')).toHaveText('Native documentation');
    await expect(page.getByRole('progressbar', { name: 'Review progress: 37%' })).toHaveAttribute('value', '37');
    await expect(page.locator('#content progress')).toHaveCSS('accent-color', 'rgb(37, 99, 235)');
    await expect(page.locator('#content img')).toHaveCount(2);
    await expect(page.locator('#content figure').filter({ has: page.getByRole('img', { name: 'Native pixels', exact: true }) }).locator('figcaption')).toHaveText('Figure caption & source evidence');
    await expect.poll(() => page.locator('#content img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBe(true);
    await page.locator('#content').getByRole('link', { name: 'Wiki evidence', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Evidence', exact: true })).toBeFocused();
    await page.locator('#content').getByRole('link', { name: 'Home', exact: true }).click();
    await page.locator('#content').getByRole('link', { name: 'Start here' }).click();
    await expect(page.locator('#content h1')).toHaveText('Getting started');
    await expect(page.getByRole('heading', { name: 'Evidence', exact: true })).toBeFocused();
    await expect(page.locator('#docMeta')).toContainText('Draft');
    await expect(page.locator('#content')).toContainText('Unsaved reviewed content.');
    await page.locator('#content').getByRole('link', { name: 'Named target', exact: true }).click();
    await expect(page.locator('#named-position')).toBeFocused();
    await expect(page.locator('#named-position')).toHaveText('Named destination');
    await page.locator('#content').getByRole('link', { name: 'Empty target', exact: true }).click();
    await expect(page.locator('#empty-position')).toBeFocused();
    await expect(page.locator('#empty-position')).toHaveText('');
    await page.goBack();
    await expect(page.locator('#named-position')).toBeFocused();
    await page.locator('#content').getByRole('link', { name: 'Home', exact: true }).click();
    await expect(page.locator('#content h1')).toHaveText('Native documentation');
    await page.goBack();
    await expect(page.locator('#content h1')).toHaveText('Getting started');
    await page.locator('#searchInput').fill('unsaved reviewed');
    await expect(page.locator('#searchResults .search-result')).toHaveCount(1);
    await expect(page.locator('#searchResults .search-result strong')).toHaveText('Evidence');
    await page.locator('#searchResults .search-result').focus();
    await page.keyboard.press('Enter');
    await expect(page.locator('#content')).toContainText('Unsaved reviewed content.');
    await expect(page.getByRole('heading', { name: 'Evidence', exact: true })).toBeFocused();
    await page.locator('#searchInput').fill('evidence');
    await page.locator('#searchInput').fill('release-ready-token');
    await expect(page.locator('#searchResults .search-result')).toHaveCount(1);
    await expect(page.locator('#searchResults .search-result strong')).toHaveText('Publishing');
    await expect(page.locator('#searchResults mark')).toHaveText('release-ready-token');
    expect(await page.locator('.skip-link').evaluate(link => link.getBoundingClientRect().bottom)).toBeLessThanOrEqual(0);
    await page.screenshot({ path: test.info().outputPath('native-site-section-search.png') });
    await page.locator('#searchResults .search-result').click();
    await expect(page.getByRole('heading', { name: 'Publishing', exact: true })).toBeFocused();
    await expect(page).toHaveURL(/\/publishing$/);
    await page.locator('#searchInput').fill('nested-section-token');
    await expect(page.locator('#searchResults .search-result strong')).toHaveText('Nested notes');
    await page.locator('#searchResults .search-result').click();
    await expect(page.getByRole('heading', { name: 'Nested notes', exact: true })).toBeFocused();
    await page.goBack();
    await expect(page.getByRole('heading', { name: 'Publishing', exact: true })).toBeFocused();
    await expect(page.locator('#content details')).toHaveCount(2);
    await expect(page.locator('#content details[open]')).toHaveCount(0);
    await page.locator('#searchInput').fill('details-search-token');
    await expect(page.locator('#searchResults .search-result strong')).toHaveText('Recovery evidence');
    await page.locator('#searchResults .search-result').click();
    await expect(page.locator('#content details[open]')).toHaveCount(2);
    await expect(page.getByRole('heading', { name: 'Recovery evidence', exact: true })).toBeFocused();
    await expect(page.locator('#content')).toContainText('Details-search-token remains available');
    await page.locator('#searchInput').fill('mathSearchToken');
    await expect(page.locator('#searchResults .search-result strong')).toHaveText('Formula evidence');
    await page.locator('#searchResults .search-result').click();
    await expect(page.getByRole('heading', { name: 'Formula evidence', exact: true })).toBeFocused();
    await expect(page.locator('#content .document-math img')).toHaveAttribute('alt', 'Q_{mathSearchToken}=\\frac{a}{b}');
    await expect(page.locator('#content .document-math img')).toHaveCSS('background-color', 'rgb(250, 250, 250)');
    await page.locator('#searchInput').fill('src=x');
    await expect(page.locator('#searchResults mark')).toHaveText('src=x');
    await expect(page.locator('#searchResults img')).toHaveCount(0);
    await page.locator('#searchInput').fill('<img onerror=unavailable()>');
    await expect(page.locator('#searchResults')).toHaveText('No results.');
    await page.locator('#searchInput').fill(Array.from({ length: 17 }, (_, index) => 'term' + index).join(' '));
    await expect(page.locator('#searchResults')).toHaveText('Use up to 16 search terms.');
    await page.locator('#searchInput').fill('');
    await expect(page.locator('#nav')).toBeVisible();
    await page.locator('#themeToggle').click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
    await page.screenshot({ path: test.info().outputPath('native-site-light.png'), fullPage: true });
    await page.locator('#themeToggle').click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
    await page.reload();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
    await page.screenshot({ path: test.info().outputPath('native-site-dark.png'), fullPage: true });
    const standalone = 'artifacts/native/validation/native-progress.html';
    await page.goto(mode === 'disk' ? pathToFileURL(path.resolve(standalone)).href : '/' + standalone);
    await expect(page.getByRole('progressbar')).toHaveCount(3);
    await expect(page.getByRole('progressbar', { name: 'Evidence & review: 37%' })).toHaveAttribute('value', '37');
    await expect(page.getByRole('progressbar', { name: 'Not started: 0%' })).toHaveAttribute('value', '0');
    await expect(page.getByRole('progressbar', { name: 'Complete: 100%' })).toHaveAttribute('value', '100');
    await expect(page.getByRole('progressbar', { name: 'Evidence & review: 37%' })).toHaveCSS('accent-color', 'rgb(37, 99, 235)');
    const figure = 'artifacts/native/validation/native-figure.html';
    await page.goto(mode === 'disk' ? pathToFileURL(path.resolve(figure)).href : '/' + figure);
    await expect(page.locator('figcaption')).toHaveText('Figure 1 — Café & evidence');
    await expect(page.getByRole('img', { name: 'Two review stages' })).toBeVisible();
    await expect.poll(() => page.locator('img').evaluate(image => image.complete && image.naturalWidth === 320)).toBe(true);
    const details = 'artifacts/native/validation/native-details.html';
    await page.goto(mode === 'disk' ? pathToFileURL(path.resolve(details)).href : '/' + details);
    await expect(page.locator('details')).toHaveCount(2);
    await expect(page.locator('#hidden-heading')).toBeHidden();
    await page.locator('summary').filter({ hasText: 'Supporting evidence — Café' }).click();
    await expect(page.locator('#hidden-heading')).toBeVisible();
    await expect(page.getByText('Nested needle 042.', { exact: true })).toBeHidden();
    await page.locator('summary').filter({ hasText: 'Nested review' }).click();
    await expect(page.getByText('Nested needle 042.', { exact: true })).toBeVisible();
    await expect.poll(() => page.locator('img').evaluateAll(images => images.length === 2 && images.every(image => image.complete && image.naturalWidth > 0))).toBe(true);
    const maths = 'artifacts/native/validation/native-maths.html';
    await page.goto(mode === 'disk' ? pathToFileURL(path.resolve(maths)).href : '/' + maths);
    await expect(page.locator('.document-math img')).toHaveCount(16);
    await expect(page.getByRole('img', { name: 'E=mc^2', exact: true })).toBeVisible();
    await expect.poll(() => page.locator('.document-math img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > image.width))).toBe(true);
    expect(await page.locator('p').first().textContent()).toContain('Inline');
    await page.screenshot({ path: test.info().outputPath('native-maths-export.png'), fullPage: true });
    expect(errors).toEqual([]);
    expect(external).toEqual([]);
  });
}
